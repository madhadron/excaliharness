// The images a task runs in (D-064): the target's dev image, built the way
// its Compose file says, and a thin derived image on top adding Claude Code.
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { IMAGE_ID, type DockerClient } from "../docker";
import { tail, type Run } from "./exec";
import type { TaskProject } from "./project";

export const DEV_IMAGE_LABEL = "org.excaliharness.dev-image";
export const BASE_IMAGE_LABEL = "org.excaliharness.base-image";
export const LAYER_LABEL = "org.excaliharness.layer-sha256";

// BuildKit won't take a bare image ID, so inputs are named by tags that carry
// the exact ID (E-008).
export const pinnedTag = (id: string) => `excaliharness-pinned:${id.replace(/^sha256:/, "")}`;

export function derivedDockerfile(devImage: string, baseImage: string): string {
  return `# Generated by Excaliharness (D-064): the project's dev image plus Claude Code.
FROM ${pinnedTag(baseImage)} AS claude
FROM ${pinnedTag(devImage)}
USER root
COPY --from=claude /usr/local/bin/claude /usr/local/bin/claude
RUN if ! command -v git >/dev/null 2>&1; then \\
      if command -v apt-get >/dev/null 2>&1; then \\
        apt-get update && apt-get install -y --no-install-recommends git ca-certificates && rm -rf /var/lib/apt/lists/*; \\
      else echo "git is missing and there is no apt-get to install it" >&2; exit 1; fi; \\
    fi
# Agents have no use for setuid/setgid programs.
RUN find / -xdev -type f -perm /6000 -exec chmod a-s {} + 2>/dev/null; true
# A new session volume copies this ownership (D-079).
RUN mkdir -p /home/agent/.claude && chown -R 1000:1000 /home/agent
ENV DISABLE_AUTOUPDATER=1
USER 1000:1000
`;
}

export class TaskImages {
  constructor(
    private readonly docker: Pick<DockerClient, "inspectImage">,
    private readonly run: Run,
    private readonly log: (line: string) => void,
  ) {}

  // Builds the dev service's image as the project defines it and returns its
  // ID. The project's own FROM lines may pull base images; that is the
  // project's choice, as when the human builds it.
  // The project's other services with a `build:` section are built in the
  // same step, since services are started without building (D-079).
  async devImage(project: TaskProject, devService: string, imageName: string, otherBuilt: string[] = [], signal?: AbortSignal): Promise<string> {
    await project.compose(["build", devService, ...otherBuilt], {
      what: "building the project's images",
      timeoutMs: 30 * 60_000,
      onLine: (line) => this.log(`[dev build] ${line}`),
      ...(signal ? { signal } : {}),
    });
    const image = await this.docker.inspectImage(imageName);
    if (!image || !IMAGE_ID.test(image.Id)) throw new Error(`the dev image ${imageName} wasn't found after building it`);
    return image.Id;
  }

  // The derived image for a dev image, reused while its labels match.
  async derived(devImage: string, baseImage: string, socketEnv: NodeJS.ProcessEnv, signal?: AbortSignal): Promise<string> {
    const dockerfile = derivedDockerfile(devImage, baseImage);
    const layer = createHash("sha256").update(dockerfile).digest("hex");
    const tag = `excaliharness-derived:${layer.slice(0, 12)}`;
    const matches = (labels: Record<string, string> | null | undefined) =>
      labels?.[DEV_IMAGE_LABEL] === devImage && labels[BASE_IMAGE_LABEL] === baseImage && labels[LAYER_LABEL] === layer;
    const existing = await this.docker.inspectImage(tag);
    if (existing && IMAGE_ID.test(existing.Id) && matches(existing.Config?.Labels)) return existing.Id;

    for (const id of [devImage, baseImage]) {
      const tagged = await this.run("docker", ["tag", id, pinnedTag(id)], { env: socketEnv, timeoutMs: 60_000 });
      if (tagged.code !== 0) throw new Error(`couldn't tag ${id} for the build:\n${tail(tagged)}`);
    }
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "excaliharness-derived-"));
    try {
      fs.writeFileSync(path.join(dir, "Dockerfile"), dockerfile);
      const iidfile = path.join(dir, "iid");
      const labels = [`${DEV_IMAGE_LABEL}=${devImage}`, `${BASE_IMAGE_LABEL}=${baseImage}`, `${LAYER_LABEL}=${layer}`].flatMap((l) => ["--label", l]);
      this.log(`building ${tag}`);
      const built = await this.run("docker", ["build", "--pull=false", "--iidfile", iidfile, ...labels, "-t", tag, dir], {
        env: socketEnv,
        timeoutMs: 20 * 60_000,
        onLine: (line) => this.log(`[derived build] ${line}`),
        ...(signal ? { signal } : {}),
      });
      if (built.code !== 0) throw new Error(`building the agent image on top of the dev image failed:\n${tail(built)}`);
      const id = fs.readFileSync(iidfile, "utf8").trim();
      if (!IMAGE_ID.test(id)) throw new Error(`docker build wrote an unexpected image ID: "${id.slice(0, 80)}"`);
      const result = await this.docker.inspectImage(id);
      if (!matches(result?.Config?.Labels)) throw new Error("the built agent image doesn't carry the expected labels");
      return id;
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
}
